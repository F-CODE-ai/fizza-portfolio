// RAG ingestion script (Module 4):
// 1. Reads content/*.md, chunks by section/heading, computes local normalized 128-d vectors
// 2. Writes content/kb-index.json and src/classic/kb-chunks.js (so both serverless /api/chat and local Vite dev work)
// 3. When SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, and GEMINI_API_KEY are set in .env, embeds each chunk with
//    Gemini text-embedding-004 (768-d) and upserts into public.kb_chunks in Supabase pgvector.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { localEmbed } from '../api/_rag.js';

function parseMarkdownChunks(dir = 'content') {
  const files = readdirSync(dir).filter((f) => f.endsWith('.md'));
  const chunks = [];
  for (const file of files) {
    const raw = readFileSync(join(dir, file), 'utf8');
    const secMatch = raw.match(/section:\s*(\w+)/);
    const section = secMatch ? secMatch[1] : file.replace(/\.md$/, '');
    const body = raw.replace(/^---[\s\S]*?---\s*/, '');
    const parts = body.split(/\n(?=##?\s)/);
    parts.forEach((p, idx) => {
      const lines = p.trim().split('\n');
      const title = lines[0].replace(/^#+\s*/, '').trim() || section;
      const content = lines
        .slice(1)
        .join(' ')
        .replace(/\s+/g, ' ')
        .trim() || title;
      chunks.push({
        id: `${section}-${idx + 1}`,
        section,
        title,
        content,
        localVec: localEmbed(`${title} ${content}`),
      });
    });
  }
  return chunks;
}

async function embedGemini768(text, apiKey) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/text-embedding-004:embedContent?key=${apiKey}`;
  const r = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: 'models/text-embedding-004',
      content: { parts: [{ text }] },
      outputDimensionality: 768,
    }),
  });
  if (!r.ok) return null;
  const d = await r.json();
  return d.embedding?.values || null;
}

const chunks = parseMarkdownChunks('content');
writeFileSync('content/kb-index.json', JSON.stringify(chunks, null, 2));
writeFileSync(
  'src/classic/kb-chunks.js',
  `// Auto-generated by scripts/ingest.mjs — do not edit by hand.\nexport const KB_CHUNKS = ${JSON.stringify(chunks.map(({ id, section, title, content }) => ({ id, section, title, content })), null, 2)};\n`
);
console.log(`Ingested ${chunks.length} chunks into content/kb-index.json and src/classic/kb-chunks.js`);

if (process.env.SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY && process.env.GEMINI_API_KEY) {
  let uploaded = 0;
  for (const c of chunks) {
    const emb = await embedGemini768(`${c.title}\n${c.content}`, process.env.GEMINI_API_KEY);
    const r = await fetch(`${process.env.SUPABASE_URL}/rest/v1/kb_chunks`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        apikey: process.env.SUPABASE_SERVICE_ROLE_KEY,
        Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY}`,
        Prefer: 'resolution=merge-duplicates',
      },
      body: JSON.stringify({
        id: c.id,
        section: c.section,
        title: c.title,
        content: c.content,
        embedding: emb,
      }),
    });
    if (r.ok) uploaded++;
  }
  console.log(`Upserted ${uploaded}/${chunks.length} chunks to Supabase pgvector.`);
}
